CREATE TABLE roles (
    id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

-- Ahora, creamos la tabla 'Usuario'.
CREATE TABLE users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    id_number VARCHAR(20) NOT NULL UNIQUE,
    phone VARCHAR(20),

    -- Esta columna será la clave foránea que se conecta con la tabla 'roles'.
    id_role INT NOT NULL,

    -- El tipo DECIMAL es ideal para valores monetarios para evitar problemas de precisión.
    base_salary DECIMAL(12, 2) NOT NULL,

    -- Aquí definimos la relación entre las tablas.
    -- La columna 'id_role' de esta tabla hace referencia a la columna 'id' de la tabla 'roles'.
    CONSTRAINT fk_user_role
        FOREIGN KEY (id_role) REFERENCES roles(id)
);